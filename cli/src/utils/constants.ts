// Stack emojis - generic, no hardcoded service names
// Users can add their own stack emojis via project config
const STACK_EMOJIS: Record<string, string> = {
  infra: "🏗️",
  core: "🔧",
  api: "⚡",
  app: "🎨",
  orchestrator: "⚙️",
} as const;

export function getStackEmoji(stackName: string): string {
  const lowerName = stackName.toLowerCase();
  for (const [key, emoji] of Object.entries(STACK_EMOJIS)) {
    if (lowerName.includes(key)) {
      return emoji;
    }
  }
  return "📦";
}
